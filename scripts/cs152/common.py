# Categorical slots in fixed order (validated for CVD separation on white).
# Several sit under 3:1 contrast, so every figure ships with a matching table.
PALETTE = ["#2a78d6", "#eb6834", "#1baf7a", "#eda100", "#e87ba4", "#008300"]
INK = "#1f1f1e"
INK_MUTED = "#6b6a64"
GRID = "#e4e3de"

FIGSIZE = (10, 4.8)
DPI = 200


