def write_json(lab, data):
    RESULTS.mkdir(parents=True, exist_ok=True)
    path = RESULTS / f"{lab}.json"
    with open(path, "w") as f:
        json.dump(data, f, indent=2, sort_keys=True)
        f.write("\n")
    return path


def load_json(lab):
    path = RESULTS / f"{lab}.json"
    if not path.is_file():
        return None
    with open(path) as f:
        return json.load(f)


def tex_escape(s):
    for a, b in (("\\", r"\textbackslash{}"), ("&", r"\&"), ("%", r"\%"),
                 ("$", r"\$"), ("#", r"\#"), ("_", r"\_")):
        s = s.replace(a, b)
    return s


def latex_table(caption, header, rows, label=None):
    """Same layout as the hand-written report tables (double rule, centered)."""
    cols = " ".join("c" for _ in header)
    out = ["% Auto-generated by scripts/analyze.py — do not edit by hand",
           r"\begin{table}[ht]", rf"\caption{{{caption}}}", r"\centering",
           rf"\begin{{tabular}}{{{cols}}}", r"\hline\hline",
           " & ".join(header) + r" \\ [0.5ex]", r"\hline"]
    out += [" & ".join(str(c) for c in r) + r" \\" for r in rows]
    out += [r"[1ex]", r"\hline", r"\end{tabular}"]
    if label:
        out.append(rf"\label{{{label}}}")
    out += [r"\end{table}", ""]
    return "\n".join(out)


def write_table(lab, name, text):
    d = TABLES / lab
    d.mkdir(parents=True, exist_ok=True)
    path = d / f"{name}.tex"
    path.write_text(text)
    return path


