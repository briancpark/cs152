def read(path):
    try:
        with open(path, errors="replace") as f:
            return f.read()
    except OSError:
        return ""


def sim_outputs(lab):
    """{config_name: Path} for labs/<lab>/sims/verilator/output/chipyard.TestHarness.<config>.

    Variant builds (see run_labs.sh) show up as <CONFIG>_<variant>.
    """
    base = LABS / lab / "sims" / "verilator" / "output"
    if not base.is_dir():
        return {}
    out = {}
    for d in sorted(base.iterdir()):
        if d.is_dir() and d.name.startswith("chipyard.TestHarness."):
            out[d.name[len("chipyard.TestHarness."):]] = d
    return out


def parse_mcycle(text):
    """Last `mcycle = N` / `minstret = N` pair printed by a benchmark."""
    out = {}
    for key in ("mcycle", "minstret"):
        vals = re.findall(rf"\b{key}\s*=\s*(\d+)", text)
        if vals:
            out[key] = int(vals[-1])
    return out


_KV_COLON = re.compile(r"^\s*([A-Za-z][\w$./ -]*?)\s*:\s*(\d+)\s*$", re.MULTILINE)

def parse_kv_colon(text):
    """`label : 123` lines (Rocket HPM counter dumps)."""
    return {k.strip().lower(): int(v) for k, v in _KV_COLON.findall(text)}


