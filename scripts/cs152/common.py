def style():
    plt.rcParams.update({
        "figure.dpi": DPI, "savefig.dpi": DPI,
        "font.size": 11, "axes.titlesize": 13, "axes.labelsize": 11,
        "axes.edgecolor": INK_MUTED, "axes.labelcolor": INK, "text.color": INK,
        "xtick.color": INK_MUTED, "ytick.color": INK_MUTED,
        "axes.spines.top": False, "axes.spines.right": False,
        "axes.grid": True, "axes.grid.axis": "y", "grid.color": GRID,
        "grid.linewidth": 0.8, "axes.axisbelow": True,
        "legend.frameon": False, "axes.prop_cycle": matplotlib.cycler(color=PALETTE),
    })


def new_fig(figsize=FIGSIZE):
    style()
    return plt.subplots(figsize=figsize)


def grouped_bars(ax, categories, series, value_fmt=None, colors=None):
    """Grouped bars: `series` is an ordered {name: [value per category]}.

    Colors follow the series order (fixed slots), bars are separated by a thin
    white gap, and `value_fmt` (e.g. "{:.2f}") labels each bar when given.
    """
    names = list(series)
    n = max(len(names), 1)
    width = 0.8 / n
    x = np.arange(len(categories))
    for i, name in enumerate(names):
        vals = [np.nan if v is None else v for v in series[name]]
        color = (colors or PALETTE)[i % len(colors or PALETTE)]
        bars = ax.bar(x + (i - (n - 1) / 2) * width, vals, width, label=name,
                      color=color, edgecolor="white", linewidth=1.2)
        if value_fmt:
            for b, v in zip(bars, vals):
                if not np.isnan(v):
                    ax.annotate(value_fmt.format(v), (b.get_x() + b.get_width() / 2, b.get_height()),
                                xytext=(0, 2), textcoords="offset points", ha="center",
                                va="bottom", fontsize=7, color=INK_MUTED)
    ax.set_xticks(x, categories)
    top = max((v for vals in series.values() for v in vals if v is not None), default=0)
    if top >= 10000:    # plain thousands instead of a "1e6" offset label
        ax.yaxis.set_major_formatter(matplotlib.ticker.FuncFormatter(lambda v, _: f"{v:,.0f}"))
    if n > 1:
        legend_below(ax, n)
    return ax


def legend_below(ax, n):
    """Legend under the plot so it never sits on top of tall bars."""
    ax.legend(ncols=min(n, 4), loc="upper center", bbox_to_anchor=(0.5, -0.2))


def save(fig, lab, name):
    d = FIGURES / lab
    d.mkdir(parents=True, exist_ok=True)
    path = d / f"{name}.png"
    fig.savefig(path, bbox_inches="tight", metadata={"Software": None})
    plt.close(fig)
    return path


def rel(path):
    return os.path.relpath(path, ROOT)
