"""Lab 4 — RVV on Spike.

Data: labs/lab4/benchmarks/<bench>.result (stdout of each Spike run + exit status).

Stock Spike has no timing model (the course's modified Spike did), so
mcycle == minstret: the comparison here is dynamic instruction count, plus the
cache statistics Spike's --ic/--dc/--l2 models report.
"""
import re

from .common import LABS, grouped_bars, latex_table, new_fig, read, save, write_table

KERNELS = ["csaxpy", "cmplxmult", "dgemv", "dgemm", "imax", "spmv", "rsort"]
_STAT = re.compile(r"^(L2\$|D\$|I\$) ([A-Za-z ]+):\s+([\d.]+)%?\s*$", re.MULTILINE)


def collect():
    base = LABS / "lab4" / "benchmarks"
    data = {}
    if not base.is_dir():
        return data
    for f in sorted(base.glob("*.result")):
        text = read(f)
        stats = {}
        for key in ("mcycle", "minstret", "exit_status"):
            vals = re.findall(rf"\b{key}\s*=\s*(\d+)", text)
            if vals:
                stats[key] = int(vals[-1])
        for cache, metric, val in _STAT.findall(text):
            stats[f"{cache} {metric.strip().lower()}"] = float(val) if "." in val else int(val)
        stats["passed"] = "FAILED" not in text and stats.get("exit_status", 0) == 0
        data[f.stem] = stats
    return data


def report(data):
    made = []
    pairs = [k for k in KERNELS if k in data and f"vec-{k}" in data]
    rows = []
    for k in KERNELS:
        s, v = data.get(k), data.get(f"vec-{k}")
        if not s and not v:
            continue
        cell = lambda r, key: (r.get(key, "--") if r and r.get("passed") else "FAIL" if r else "--")
        ratio = (f"{s['minstret'] / v['minstret']:.1f}x"
                 if s and v and s.get("passed") and v.get("passed") and v.get("minstret") else "--")
        rows.append([k, cell(s, "minstret"), cell(v, "minstret"), ratio,
                     cell(s, "D$ miss rate"), cell(v, "D$ miss rate")])
    if rows:
        made.append(write_table("lab4", "summary", latex_table(
            "Scalar vs vector on Spike (instruction counts; stock Spike has no timing model)",
            ["Kernel", "Scalar instret", "Vector instret", "Reduction", "Scalar D\\$ miss \\%",
             "Vector D\\$ miss \\%"], rows)))

    ok = [k for k in pairs if data[k].get("passed") and data[f"vec-{k}"].get("passed")]
    if ok:
        fig, ax = new_fig()
        grouped_bars(ax, ok, {"Scalar": [data[k]["minstret"] for k in ok],
                              "Vector": [data[f"vec-{k}"]["minstret"] for k in ok]})
        ax.set_yscale("log")
        ax.set_title("Dynamic instruction count, scalar vs vector (Spike)")
        ax.set_ylabel("Instructions retired (log scale)")
        made.append(save(fig, "lab4", "instret"))

        fig, ax = new_fig()
        grouped_bars(ax, ok, {"Scalar": [data[k]["D$ read accesses"] + data[k]["D$ write accesses"] for k in ok],
                              "Vector": [data[f"vec-{k}"]["D$ read accesses"] + data[f"vec-{k}"]["D$ write accesses"]
                                         for k in ok]})
        ax.set_title("L1 D$ accesses, scalar vs vector (Spike cache model)"); ax.set_ylabel("Accesses")
        made.append(save(fig, "lab4", "dcache_accesses"))

    for k in KERNELS:   # the verbatim-stat blocks the report quotes, one per kernel
        for name in (k, f"vec-{k}"):
            s = data.get(name)
            if s and s.get("passed"):
                lines = [f"mcycle = {s.get('mcycle')}", f"minstret = {s.get('minstret')}"]
                lines += [f"{key}: {s[key]}" for key in sorted(s) if key[:2] in ("L2", "D$", "I$")]
                made.append(write_table("lab4", f"stats_{name}",
                                        "% Auto-generated by scripts/analyze.py\n\\begin{verbatim}\n"
                                        + "\n".join(lines) + "\n\\end{verbatim}\n"))
    return made
